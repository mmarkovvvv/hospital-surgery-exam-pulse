export type UsmleFormat = 'card' | 'test' | 'ticket' | 'case' | 'image-case'

export type UsmleImportRecord = {
  title: string
  slug: string
  subject: 'USMLE'
  format: UsmleFormat
  visibility: 'public' | 'registered' | 'subscription'
  published: true
  summary: string
  question: string
  answer: string
  sourceData: Record<string, unknown>
}

const card = (
  slug: string,
  title: string,
  summary: string,
  question: string,
  answer: string,
  visibility: UsmleImportRecord['visibility'] = 'registered',
): UsmleImportRecord => ({
  title,
  slug: `usmle-card-${slug}`,
  subject: 'USMLE',
  format: 'card',
  visibility,
  published: true,
  summary,
  question,
  answer,
  sourceData: { topic: 'USMLE', type: 'original-card' },
})

const test = (
  slug: string,
  title: string,
  summary: string,
  question: string,
  answer: string,
  options: Array<{ id: string; text: string; correct?: boolean }>,
  multiple = false,
  visibility: UsmleImportRecord['visibility'] = 'registered',
): UsmleImportRecord => ({
  title,
  slug: `usmle-test-${slug}`,
  subject: 'USMLE',
  format: 'test',
  visibility,
  published: true,
  summary,
  question,
  answer,
  sourceData: { topic: 'USMLE', type: 'original-test', multiple, options },
})

const ticket = (
  slug: string,
  title: string,
  summary: string,
  answer: string,
  answerPlan: Array<[string, string]>,
  tag: string,
  visibility: UsmleImportRecord['visibility'] = 'registered',
): UsmleImportRecord => ({
  title,
  slug: `usmle-ticket-${slug}`,
  subject: 'USMLE',
  format: 'ticket',
  visibility,
  published: true,
  summary,
  question: title,
  answer,
  sourceData: { topic: 'USMLE', type: 'original-ticket', tag, category: tag, answerPlan },
})

const clinicalCase = (
  slug: string,
  title: string,
  summary: string,
  answer: string,
  diagnosis: string,
  steps: string[],
  visibility: UsmleImportRecord['visibility'] = 'registered',
): UsmleImportRecord => ({
  title,
  slug: `usmle-case-${slug}`,
  subject: 'USMLE',
  format: 'case',
  visibility,
  published: true,
  summary,
  question: summary,
  answer,
  sourceData: { topic: 'USMLE', type: 'original-case', diagnosis, steps },
})

const imageCase = (
  slug: string,
  title: string,
  summary: string,
  image: string,
  imageAlt: string,
  answer: string,
  diagnosis: string,
  steps: string[],
): UsmleImportRecord => ({
  title,
  slug: `usmle-image-case-${slug}`,
  subject: 'USMLE',
  format: 'image-case',
  visibility: 'registered',
  published: true,
  summary,
  question: summary,
  answer,
  sourceData: {
    topic: 'USMLE',
    type: 'original-image-case',
    image,
    imageAlt,
    sourceTitle: 'Авторская учебная схема Beep Academy',
    license: 'Оригинальная схема для учебного курса',
    diagnosis,
    steps,
  },
})

